let currentLang = 'fr';

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  try { localStorage.setItem('sux-lang', lang); } catch(e) {}
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang')));
});

// Restore saved language preference
try {
  const saved = localStorage.getItem('sux-lang');
  if (saved && translations[saved]) setLang(saved);
} catch(e) {}

// ── Scroll reveal ──
const observer = new IntersectionObserver((entries) => {
  entries.forEach(e => { if (e.isIntersecting) { e.target.classList.add('visible'); observer.unobserve(e.target); } });
}, { threshold: 0.15, rootMargin: '0px 0px -40px 0px' });
document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

// ── Nav scroll ──
let ticking = false;
window.addEventListener('scroll', () => {
  if (!ticking) { requestAnimationFrame(() => { document.querySelector('nav').classList.toggle('scrolled', window.scrollY > 60); ticking = false; }); ticking = true; }
});

// ── Waveform canvas ──
(function() {
  const canvas = document.getElementById('waveform');
  if (!canvas) return;
  const ctx = canvas.getContext('2d');
  let w, h, time = 0;

  function resize() {
    const rect = canvas.parentElement.getBoundingClientRect();
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    w = canvas.width = rect.width * 0.45 * dpr;
    h = canvas.height = rect.height * 0.6 * dpr;
    canvas.style.width = rect.width * 0.45 + 'px';
    canvas.style.height = rect.height * 0.6 + 'px';
    ctx.scale(dpr, dpr);
  }
  resize();
  window.addEventListener('resize', resize);

  function draw() {
    const cw = w / (window.devicePixelRatio || 1);
    const ch = h / (window.devicePixelRatio || 1);
    ctx.clearRect(0, 0, cw, ch);

    for (let j = 0; j < 5; j++) {
      ctx.beginPath();
      ctx.strokeStyle = `rgba(90, 115, 255, ${0.12 + j * 0.06})`;
      ctx.lineWidth = 1;
      const freq = 0.008 + j * 0.003;
      const amp = ch * (0.08 + j * 0.03);
      const speed = 0.015 + j * 0.005;
      for (let x = 0; x <= cw; x += 2) {
        const y = ch / 2 + Math.sin(x * freq + time * speed) * amp * Math.sin(x * 0.003 + time * 0.008);
        x === 0 ? ctx.moveTo(x, y) : ctx.lineTo(x, y);
      }
      ctx.stroke();
    }
    time++;
    requestAnimationFrame(draw);
  }
  draw();
})();
